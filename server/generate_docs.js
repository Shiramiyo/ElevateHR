const fs = require('fs');
const path = require('path');
const { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, BorderStyle } = require('docx');

function createTranscriptDoc(title, subtitle, filename, sections) {
  const children = [];

  // Title
  children.push(
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 200, after: 120 },
      children: [
        new TextRun({
          text: title,
          bold: true,
          size: 32, // 16pt
          font: 'Calibri'
        })
      ]
    })
  );

  // Subtitle
  children.push(
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 300 },
      children: [
        new TextRun({
          text: subtitle,
          italics: true,
          size: 22, // 11pt
          color: '555555',
          font: 'Calibri'
        })
      ]
    })
  );

  // Divider
  children.push(
    new Paragraph({
      spacing: { after: 300 },
      border: {
        bottom: {
          color: 'CCCCCC',
          space: 1,
          style: BorderStyle.SINGLE,
          size: 6
        }
      }
    })
  );

  // Content Sections
  for (const sec of sections) {
    if (sec.heading) {
      children.push(
        new Paragraph({
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 280, after: 140 },
          children: [
            new TextRun({
              text: sec.heading,
              bold: true,
              size: 26, // 13pt
              color: '1E3A8A',
              font: 'Calibri'
            })
          ]
        })
      );
    }

    for (const item of sec.items) {
      if (item.speaker) {
        children.push(
          new Paragraph({
            spacing: { before: 140, after: 60 },
            children: [
              new TextRun({
                text: item.speaker + ':',
                bold: true,
                size: 22,
                color: '0F172A',
                font: 'Calibri'
              })
            ]
          })
        );
      }

      if (item.text) {
        children.push(
          new Paragraph({
            spacing: { before: 40, after: 140 },
            children: [
              new TextRun({
                text: item.text,
                size: 22,
                font: 'Calibri'
              })
            ]
          })
        );
      }
    }
  }

  const doc = new Document({
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: 1440, // 1 inch
              right: 1440,
              bottom: 1440,
              left: 1440
            }
          }
        },
        children
      }
    ]
  });

  return Packer.toBuffer(doc).then(buffer => {
    fs.writeFileSync(filename, buffer);
    console.log('Saved:', filename);
  });
}

